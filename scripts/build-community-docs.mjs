#!/usr/bin/env node
/** Keep the public feature index derived from the one canonical catalogue. No dependencies/network. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: node scripts/build-community-docs.mjs [--check]');
const { categories, tools } = JSON.parse(fs.readFileSync(path.join(root, 'catalog/tools.json'), 'utf8'));
const cell = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('|', '&#124;').replace(/[\r\n]+/g, ' ');
const platforms = { windows: 'Windows', macos: 'macOS', linux: 'Linux' };
const content = `<!-- Generated by node scripts/build-community-docs.mjs. Edit catalog/tools.json, not this file. -->
# Feature catalogue

Oxbox has ${tools.length} implemented tool routes in ${categories.length} categories. The platform column describes source
availability, not completed manual certification. Review [usage](USAGE.md), [provider limits](ROADMAP_TOOLS.md),
the [native acceptance matrix](../tasks/native-migration.md), [maintenance scope](MAINTENANCE.md) and [release gates](RELEASE.md) before inferring
support. Hardware, OS/session permissions and optional local providers can limit individual actions.

${categories.map(category => `## ${cell(category.label)}

| Tool / stable ID | Purpose | Platforms in source | Limits / notes |
|---|---|---|---|
${tools.filter(tool => tool.category === category.id).map(tool => `| **${cell(tool.name)}**<br>\`${cell(tool.id)}\` | ${cell(tool.description)} | ${tool.platforms.map(os => { if (!platforms[os]) throw new Error('Unknown platform: ' + os); return platforms[os]; }).join(', ')} | ${cell(tool.note || 'See the usage guide and acceptance matrix.')} |`).join('\n')}`).join('\n\n')}

## Contribute

Start with [the contribution walkthrough](GETTING_STARTED.md). Use the stable ID in bug reports and regression
tests. Update the canonical catalogue and run \`node scripts/build-community-docs.mjs\` when metadata changes;
CI uses \`--check\` to detect stale generated documentation. The native, legacy and website interfaces read
the same metadata. See [catalogue maintenance](../catalog/README.md).
`;
const output = path.join(root, 'docs/FEATURES.md');
if (args.includes('--check')) {
  const actual = fs.existsSync(output) ? fs.readFileSync(output, 'utf8').replaceAll('\r\n', '\n') : '';
  if (actual !== content) throw new Error('docs/FEATURES.md is stale. Run node scripts/build-community-docs.mjs.');
  console.log(`Community feature index matches ${tools.length} canonical tools.`);
} else {
  fs.writeFileSync(output, content);
  console.log(`Generated docs/FEATURES.md from ${tools.length} canonical tools.`);
}
